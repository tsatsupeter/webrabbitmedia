// Generates src/pages/docs/corpus.js — plain-text extraction of every docs page,
// used to ground the docs Assistant in real documentation content.
// Run: node scripts/build-docs-corpus.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const docsDir = path.join(root, 'src/pages/docs')
const registrySrc = fs.readFileSync(path.join(docsDir, 'registry.js'), 'utf8')

// component name -> file
const imports = {}
for (const m of registrySrc.matchAll(/import\s+(\w+)\s+from\s+'\.\/sections\/(\w+)'/g)) {
  imports[m[1]] = m[2]
}

// slug/title/summary/Component blocks
const pages = []
const blockRe = /slug:\s*'([^']+)',\s*\n\s*title:\s*'([^']*)',\s*\n\s*summary:\s*'([^']*)',\s*\n\s*Component:\s*(\w+)/g
for (const m of registrySrc.matchAll(blockRe)) {
  pages.push({ slug: m[1], title: m[2], summary: m[3], component: m[4] })
}

function toText(jsx) {
  let s = jsx
  s = s.replace(/^import[\s\S]*?from\s+'[^']+'\n/gm, '')
  s = s.replace(/\/\*[\s\S]*?\*\//g, ' ')
  s = s.replace(/^\s*\/\/.*$/gm, ' ')
  // keep template/string literals (code samples, tables) as text
  s = s.replace(/`([^`]*)`/g, (_, inner) => ' ' + inner + ' ')
  s = s.replace(/\{\s*'([^']*)'\s*\}/g, ' $1 ')
  s = s.replace(/\{[^{}]*\}/g, ' ') // remaining JSX expressions
  s = s.replace(/<[^>]+>/g, ' ') // tags
  s = s.replace(/&rsquo;|&#39;/g, "'").replace(/&amp;/g, '&').replace(/&mdash;/g, '—')
  s = s.replace(/[ \t]+/g, ' ').replace(/\n\s*\n\s*\n+/g, '\n\n')
  return s.trim()
}

const out = pages.map((p) => {
  const file = imports[p.component]
  const jsx = file ? fs.readFileSync(path.join(docsDir, 'sections', `${file}.jsx`), 'utf8') : ''
  let text = toText(jsx)
  if (text.length > 9000) text = text.slice(0, 9000)
  return { slug: p.slug, title: p.title, summary: p.summary, text }
})

const banner = `// AUTO-GENERATED by scripts/build-docs-corpus.mjs — do not edit by hand.
// Plain-text docs corpus used to ground the docs Assistant.
export const corpus = `

fs.writeFileSync(
  path.join(docsDir, 'corpus.js'),
  banner + JSON.stringify(out, null, 2) + '\n',
)
console.log(`docs corpus: ${out.length} pages`)
